// ── Damage overlay ────────────────────────────────────────────────────────────
function applyShipDamage(sprite, level, seed = 0) {
  if (level === 0) return sprite;
  const rows = sprite.trim().split('\n').map(r => r.split(''));
  const h    = rows.length;
  const rand = n => { const x = Math.sin(seed*9301 + n*49297)*233280; return x - Math.floor(x); };
  const hull = [];
  for (let y=0;y<h;y++) for (let x=0;x<rows[y].length;x++) {
    if (rows[y][x]!=='.'&&rows[y][x]!=='8') hull.push([x,y]);
  }
  if (level>=1) {
    const n=Math.floor(hull.length*.10);
    for (let i=0;i<n;i++){const[x,y]=hull[Math.floor(rand(i+1)*hull.length)];rows[y][x]='1';}
    for (let i=0;i<3;i++){const sx=Math.floor(rand(i+7)*rows[0].length);if(rows[0][sx]==='.')rows[0][sx]='9';}
  }
  if (level>=2){const f=Math.floor(hull.length*.14);for(let i=0;i<f;i++){const[x,y]=hull[Math.floor(rand(i+17)*hull.length)];rows[y][x]=i%2?'a':'b';}}
  if (level>=3){const d=Math.floor(hull.length*.32);for(let i=0;i<d;i++){const[x,y]=hull[Math.floor(rand(i+41)*hull.length)];rows[y][x]=i%3===0?'.':i%3===1?'c':'a';}}
  if (level>=4) for(let y=0;y<h;y++) for(let x=0;x<rows[y].length;x++) {
    if(rows[y][x]!=='.'){const r=rand(y*100+x);rows[y][x]=r<.25?'.':r<.55?'a':r<.8?'b':'c';}
  }
  return rows.map(r=>r.join('')).join('\n');
}

function paletteFor(color) {
  return { ...(SHIP_PALETTES[color]||SHIP_PALETTES.blue), 'a':'#ff6a1f','b':'#ffd54a','c':'#ff1a3a' };
}

// ── PixelArt renderer ──────────────────────────────────────────────────────────
function PixelArt({ grid, palette, pixel = 4 }) {
  const rows = useMemo(() => grid.trim().split('\n'), [grid]);
  const h    = rows.length;
  const w    = Math.max(...rows.map(r=>r.length));
  return (
    <div className="pixel-grid pixel" style={{
      gridTemplateColumns: `repeat(${w}, ${pixel}px)`,
      gridTemplateRows:    `repeat(${h}, ${pixel}px)`,
    }}>
      {rows.flatMap((row,y) =>
        Array.from({length:w}).map((_,x) => {
          const c = row[x]||'.';
          return <i key={`${x}-${y}`} style={{ background: c==='.' ? 'transparent' : (palette[c]||'#f0f') }}/>;
        })
      )}
    </div>
  );
}

// ── Public ShipIcon component ──────────────────────────────────────────────────
export function ShipIcon({ ship='cruiser', color='blue', damage=0, pixel=4 }) {
  const sprite  = SHIPS[ship] || SHIPS.cruiser;
  const grid    = useMemo(() => applyShipDamage(sprite, damage, ship.length+(color?.length||0)*7), [sprite, damage, ship, color]);
  const palette = useMemo(() => paletteFor(color), [color]);
  return <PixelArt grid={grid} palette={palette} pixel={pixel}/>;
}

