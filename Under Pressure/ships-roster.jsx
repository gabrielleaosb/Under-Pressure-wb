// 5 damage overlays per ship — apply progressive damage transformations
function applyShipDamage(sprite, level, seed = 0) {
  if (level === 0) return sprite;
  const rows = sprite.trim().split('\n').map(r => r.split(''));
  const h = rows.length;
  const rand = (n) => {
    const x = Math.sin(seed * 9301 + n * 49297) * 233280;
    return x - Math.floor(x);
  };
  // collect hull coords
  const hull = [];
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < rows[y].length; x++) {
      if (rows[y][x] !== '.' && rows[y][x] !== '8') hull.push([x, y]);
    }
  }
  if (level >= 1) {
    // light scratches
    const n = Math.floor(hull.length * 0.10);
    for (let i = 0; i < n; i++) {
      const [x, y] = hull[Math.floor(rand(i + 1) * hull.length)];
      rows[y][x] = '1';
    }
    // smoke wisps at top
    for (let i = 0; i < 3; i++) {
      const sx = Math.floor(rand(i + 7) * rows[0].length);
      if (rows[0][sx] === '.') rows[0][sx] = '9';
    }
  }
  if (level >= 2) {
    // fire patches (use chars 'a' fire-orange and 'b' fire-yellow — extend palette)
    const fires = Math.floor(hull.length * 0.14);
    for (let i = 0; i < fires; i++) {
      const [x, y] = hull[Math.floor(rand(i + 17) * hull.length)];
      rows[y][x] = i % 2 ? 'a' : 'b';
    }
  }
  if (level >= 3) {
    const destroyed = Math.floor(hull.length * 0.32);
    for (let i = 0; i < destroyed; i++) {
      const [x, y] = hull[Math.floor(rand(i + 41) * hull.length)];
      rows[y][x] = (i % 3 === 0) ? '.' : (i % 3 === 1) ? 'c' : 'a';
    }
  }
  if (level >= 4) {
    // explosion: scatter fire+empty
    for (let y = 0; y < h; y++) {
      for (let x = 0; x < rows[y].length; x++) {
        if (rows[y][x] !== '.') {
          const r = rand(y * 100 + x);
          if (r < 0.25) rows[y][x] = '.';
          else if (r < 0.55) rows[y][x] = 'a';
          else if (r < 0.8) rows[y][x] = 'b';
          else rows[y][x] = 'c';
        }
      }
    }
  }
  return rows.map(r => r.join('')).join('\n');
}

// Extended palette w/ fire & damage chars
function shipPaletteFor(color) {
  const base = SHIP_PALETTES[color] || SHIP_PALETTES.blue;
  return {
    ...base,
    'a': '#ff6a1f',  // fire orange
    'b': '#ffd54a',  // fire yellow
    'c': '#ff1a3a',  // critical
  };
}

// Render one ship: sprite ID + color theme + damage + pixel size
const { useMemo: __useMemoR } = React;
function ShipIcon({ ship = 'cruiser', color = 'blue', damage = 0, pixel = 4, glow = false, shake = false }) {
  const sprite = SHIPS[ship] || SHIPS.cruiser;
  const grid = __useMemoR(() => applyShipDamage(sprite, damage, ship.length + (color?.length || 0) * 7), [sprite, damage, ship, color]);
  const palette = shipPaletteFor(color);
  return <PixelArt grid={grid} palette={palette} pixel={pixel} glow={glow} shake={shake} />;
}

